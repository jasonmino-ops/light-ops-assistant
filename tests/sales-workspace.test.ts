assert.match(auth, /checkOpsAuthContext/)
assert.match(auth, /context\.role === 'OPS_ADMIN' \|\| context\.role === 'SUPER_ADMIN'/)
assert.match(list, /const currentOwnerWhere:[\s\S]+salesOwnerId: actor\.userId/)
