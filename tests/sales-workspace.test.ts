assert.match(page, /sales-shell/)
assert.match(page, /grid-template-columns:minmax\(180px,220px\) minmax\(300px,370px\)/)
assert.match(page, /setLang\(option\.code\)/)
assert.match(page, /salesWorkspace\.telegramUsername/)
assert.match(page, /@media\(max-width:360px\)/)
assert.match(page, /\/api\/sales\/messages/)
assert.doesNotMatch(page, /\/api\/ops\/store-applications|rejectApplication|banApplication|unbanApplication/i)

console.log('sales workspace tests passed')
